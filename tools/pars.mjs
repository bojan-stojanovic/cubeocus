// Run: node tools/pars.mjs  (npm run pars) -> rewrites src/pars.js so packs sort easy -> hard.
import fs from 'node:fs';
import { LEVELS } from '../src/levels.js';
import { parseLevel, solve } from '../src/logic.js';

const pars = {};
for (const def of LEVELS) {
  if (pars[def.name] !== undefined) throw new Error('Duplicate level name: ' + def.name);
  pars[def.name] = solve(parseLevel(def), 1000000);
}
const body = Object.entries(pars).map(([n, p]) => `  ${JSON.stringify(n)}: ${p},`).join('\n');
fs.writeFileSync(new URL('../src/pars.js', import.meta.url), `// Generated by tools/pars.mjs (npm run pars). Minimum moves per level; used to order each pack.\nexport const PARS = {\n${body}\n};\n`);
console.log(`wrote ${Object.keys(pars).length} pars`);
